"""Claude Code headless wrapper for the chat orchestrator (SPEC §5.1, §5.4).

One Claude session per chat thread: the first turn passes `--session-id <uuid>` (generated by
us and stored on the chat), later turns `--resume <uuid>`. Each turn is one `claude -p`
process reading the prompt from stdin and writing `stream-json` events, which we turn into
`TurnEvent`s (text deltas, tool calls, the final result).

Flags (checked against `claude --help`, v2.1.196; recorded in docs/decisions.md):
  -p --output-format stream-json --verbose --include-partial-messages
  --session-id / --resume, --model, --effort, --system-prompt
  --mcp-config <json> --strict-mcp-config      only our MCP server
  --tools ""                                   no built-in tools (no shell, no file edits)
  --allowedTools mcp__wyrd__…                  our tools, pre-approved
  --permission-mode dontAsk                    anything else is denied, never prompted
  --setting-sources "" --disable-slash-commands   no user hooks/plugins/skills
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import logging
import os
import shutil
import time
import uuid
from collections.abc import AsyncIterator, Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from apps.api import prompts
from apps.api.config import OrchestratorConfig, load_channels
from apps.api.mcp_server import CHAT_HEADER, SERVER_NAME, TOKEN, TOKEN_HEADER, agents_brief
from apps.api.mcp_server import allowed_tools as mcp_allowed_tools

log = logging.getLogger(__name__)

API_URL = os.environ.get("WYRD_API_URL", "http://127.0.0.1:8000")
STDERR_TAIL = 2000


class OrchestratorError(RuntimeError):
    pass


@dataclass
class TurnEvent:
    kind: str  # "text" | "tool" | "rate_limit" | "result"
    text: str = ""
    tool: str = ""
    data: dict[str, Any] = field(default_factory=dict)


@dataclass
class TurnResult:
    text: str
    ok: bool
    session_id: str | None
    duration_ms: int
    turns: int
    tokens_in: int
    tokens_out: int
    model: str | None
    tools: list[str]
    error: str | None = None
    rate_limit: dict[str, Any] | None = None


def system_prompt() -> str:
    channels = ", ".join(f"{c.name} = {c.handle}" for c in load_channels().channels)
    return prompts.render("orchestrator", agents=agents_brief(), channels=channels)


def mcp_config(chat_id: int) -> str:
    return json.dumps(
        {
            "mcpServers": {
                SERVER_NAME: {
                    "type": "http",
                    "url": f"{API_URL}/mcp/",
                    "headers": {CHAT_HEADER: str(chat_id), TOKEN_HEADER: TOKEN},
                }
            }
        }
    )


def build_command(
    exe: str, cfg: OrchestratorConfig, chat_id: int, session_id: str, resume: bool
) -> list[str]:
    cmd = [
        exe,
        "-p",
        "--output-format",
        "stream-json",
        "--verbose",
        "--include-partial-messages",
        "--resume" if resume else "--session-id",
        session_id,
        "--model",
        cfg.model,
        "--system-prompt",
        system_prompt(),
        "--mcp-config",
        mcp_config(chat_id),
        "--strict-mcp-config",
        "--tools",
        "",
        "--allowedTools",
        ",".join(mcp_allowed_tools()),
        "--permission-mode",
        "dontAsk",
        "--setting-sources",
        "",
        "--disable-slash-commands",
    ]
    if cfg.effort:
        cmd += ["--effort", cfg.effort]
    return cmd


def workdir(cfg: OrchestratorConfig) -> Path:
    path = Path(cfg.workdir).expanduser()
    path.mkdir(parents=True, exist_ok=True)
    return path


def short_tool_name(name: str) -> str:
    prefix = f"mcp__{SERVER_NAME}__"
    return name[len(prefix) :] if name.startswith(prefix) else name


def parse_line(line: str, acc: dict[str, Any]) -> list[TurnEvent]:
    """One stream-json line → events. `acc` collects the final result across lines."""
    try:
        msg = json.loads(line)
    except json.JSONDecodeError:
        return []
    kind = msg.get("type")
    out: list[TurnEvent] = []
    if kind == "system" and msg.get("subtype") == "init":
        acc["model"] = msg.get("model")
        acc["session_id"] = msg.get("session_id")
        acc["mcp_servers"] = msg.get("mcp_servers")
    elif kind == "stream_event":
        event = msg.get("event") or {}
        if event.get("type") == "content_block_delta":
            delta = event.get("delta") or {}
            if delta.get("type") == "text_delta" and delta.get("text"):
                out.append(TurnEvent("text", text=delta["text"]))
        elif event.get("type") == "content_block_start":
            block = event.get("content_block") or {}
            if block.get("type") == "text" and acc.get("texts"):
                out.append(TurnEvent("text", text="\n\n"))  # separate text blocks
    elif kind == "assistant":
        message = msg.get("message") or {}
        if message.get("id"):
            acc.setdefault("turn_ids", set()).add(message["id"])
        for block in message.get("content") or []:
            if block.get("type") == "text" and block.get("text"):
                acc.setdefault("texts", []).append(block["text"])
            elif block.get("type") == "tool_use":
                name = short_tool_name(block.get("name", ""))
                acc.setdefault("tools", []).append(name)
                out.append(TurnEvent("tool", tool=name, data={"input": block.get("input")}))
    elif kind == "rate_limit_event":
        info = msg.get("rate_limit_info") or {}
        acc["rate_limit"] = info
        out.append(TurnEvent("rate_limit", data=info))
    elif kind == "result":
        acc["result"] = msg
        out.append(TurnEvent("result", data=msg))
    return out


def finish(acc: dict[str, Any], returncode: int, stderr: str, elapsed_ms: int) -> TurnResult:
    result = acc.get("result") or {}
    usage = result.get("usage") or {}
    text = "\n\n".join(acc.get("texts", [])).strip()
    ok = bool(result) and not result.get("is_error") and returncode == 0
    error = None
    if not ok:
        error = (
            (result.get("result") if result.get("is_error") else None)
            or stderr.strip()[-STDERR_TAIL:]
            or f"claude exited with code {returncode}"
        )
        lowered = error.lower()
        if "login" in lowered or "not logged in" in lowered or "authenticat" in lowered:
            error += " — run `claude auth login` in a terminal, then retry."
    return TurnResult(
        text=text or (str(result.get("result") or "") if ok else ""),
        ok=ok,
        session_id=result.get("session_id") or acc.get("session_id"),
        duration_ms=int(result.get("duration_ms") or elapsed_ms),
        turns=int(result.get("num_turns") or len(acc.get("turn_ids", ()))),
        tokens_in=int(usage.get("input_tokens") or 0)
        + int(usage.get("cache_read_input_tokens") or 0)
        + int(usage.get("cache_creation_input_tokens") or 0),
        tokens_out=int(usage.get("output_tokens") or 0),
        model=acc.get("model"),
        tools=list(acc.get("tools", [])),
        error=error,
        rate_limit=acc.get("rate_limit"),
    )


MCP_CONNECT_ATTEMPTS = 3


def mcp_ready(acc: dict[str, Any]) -> bool:
    servers = acc.get("mcp_servers") or []
    return any(m.get("name") == SERVER_NAME and m.get("status") == "connected" for m in servers)


async def run_turn(
    cfg: OrchestratorConfig,
    chat_id: int,
    session_id: str,
    resume: bool,
    prompt: str,
) -> AsyncIterator[TurnEvent | TurnResult]:
    """Run one chat turn. Yields TurnEvents while streaming, then exactly one TurnResult.

    A first turn that has to be restarted (see `stream_claude`) retries with a fresh session id
    (the killed attempt may have registered the old one); the TurnResult says which was used.
    """
    exe = shutil.which("claude")
    if exe is None:
        raise OrchestratorError("Claude Code CLI not found on PATH")
    sid = [session_id]

    def command(attempt: int) -> list[str]:
        if attempt > 1 and not resume:
            sid[0] = str(uuid.uuid4())
        return build_command(exe, cfg, chat_id, sid[0], resume)

    async for event in stream_claude(
        command, workdir(cfg), prompt, cfg.turn_timeout_s, f"chat {chat_id}"
    ):
        if isinstance(event, TurnResult):
            event.session_id = event.session_id or sid[0]
        yield event


async def stream_claude(
    command: Callable[[int], list[str]],
    cwd: Path,
    prompt: str,
    timeout_s: float,
    label: str,
    max_turns: int | None = None,
) -> AsyncIterator[TurnEvent | TurnResult]:
    """Run `claude -p` (stream-json) and yield TurnEvents, then exactly one TurnResult.

    Claude Code sometimes starts the session before our MCP server has connected (init shows
    it "pending"), and then offers no tools. That attempt is killed right after the init
    event, before any model call, and retried (`command(attempt)` builds each attempt).
    `max_turns` (model calls) is a hard cap: the process is stopped once it's exceeded.
    """
    start = time.monotonic()
    deadline = start + timeout_s
    for attempt in range(1, MCP_CONNECT_ATTEMPTS + 1):
        proc = await asyncio.create_subprocess_exec(
            *command(attempt),
            cwd=cwd,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            limit=16 * 1024 * 1024,  # stream-json lines can be long
        )
        assert proc.stdin and proc.stdout and proc.stderr
        proc.stdin.write(prompt.encode())
        await proc.stdin.drain()
        proc.stdin.close()
        stderr_task = asyncio.ensure_future(proc.stderr.read())
        acc: dict[str, Any] = {}
        retry = over_budget = False
        try:
            while True:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise TimeoutError
                line = await asyncio.wait_for(proc.stdout.readline(), remaining)
                if not line:
                    break
                events = parse_line(line.decode(errors="replace"), acc)
                if "mcp_servers" in acc and not acc.get("mcp_checked"):
                    acc["mcp_checked"] = True
                    if not mcp_ready(acc):
                        retry = True
                        break
                for event in events:
                    yield event
                if max_turns is not None and len(acc.get("turn_ids", ())) > max_turns:
                    over_budget = True
                    break
            if retry:
                proc.kill()
                await proc.wait()
                stderr_task.cancel()
                if attempt == MCP_CONNECT_ATTEMPTS:
                    acc["result"] = {
                        "is_error": True,
                        "result": "The engine's MCP tools didn't connect to Claude Code "
                        f"after {attempt} tries. Is the API running on {API_URL}?",
                    }
                    yield finish(acc, -1, "", int((time.monotonic() - start) * 1000))
                    return
                log.info("%s: MCP not connected at start (attempt %d), retrying", label, attempt)
                await asyncio.sleep(0.5 * attempt)
                continue
            if over_budget:
                proc.kill()
                await proc.wait()
                acc["result"] = {
                    "is_error": True,
                    "result": f"Stopped at the turn budget ({max_turns} turns).",
                    "num_turns": max_turns,
                }
                returncode = -1
            else:
                returncode = await proc.wait()
        except TimeoutError:
            proc.kill()
            await proc.wait()
            acc["result"] = {
                "is_error": True,
                "result": f"Claude took longer than {timeout_s:.0f}s and was stopped.",
            }
            returncode = -1
        except (asyncio.CancelledError, GeneratorExit):
            with contextlib.suppress(ProcessLookupError):
                proc.kill()
            raise
        stderr = (await stderr_task).decode(errors="replace")
        yield finish(acc, returncode, stderr, int((time.monotonic() - start) * 1000))
        return
